/// Как разложить ответ сервера после `NsgBaseController.postItems` по спискам
/// контроллера.
///
/// ## Откуда взялось
///
/// NSG-SOFT/futbolista-tasks#1703 (и #1732 тем же корнем). `postItems`
/// обновлял мастер-список **только для элементов, которые в нём уже были**:
///
/// ```dart
/// old = dataItemList.firstWhereOrNull((e) => e.id == item.id);
/// if (old != null) { old.copyFieldValues(item); … }
/// // ветки «а если это новый элемент — добавить» не было
/// ```
///
/// Значит объект, СОЗДАННЫЙ приложением и сохранённый пачкой, уезжал на сервер
/// и в `items` контроллера не попадал. Экран, который строит вид из `items`,
/// сохранённого объекта не видел до перечитывания с сервера. У организатора
/// это выглядело так: разложил матчи по турам, нажал «Сохранить», переключил
/// группу, вернулся — **все туры пустые**, хотя на сервере матчи есть.
///
/// ## Почему это именно недосмотр, а не замысел
///
/// Соседние методы того же контроллера ведут себя ровно наоборот:
///
/// * `itemPagePost` (сохранение ОДНОГО элемента) после успешного поста делает
///   `if (!dataItemList.contains(selectedItem)) dataItemList.insert(...)` —
///   то есть новый элемент в список кладёт;
/// * `deleteItems` из `dataItemList` элемент **удаляет**.
///
/// Получалось, что удаление список правит, одиночное сохранение правит, а
/// пакетное — нет. Здесь эта асимметрия и снимается.
///
/// ## Инвариант, ради которого правило вынесено отдельной функцией
///
/// **Добавлять ровно тех, кого ещё нет, и ровно по одному разу.** В
/// `postItems` приходят вперемешку и новые объекты, и отредактированные
/// старые (кнопка «Сохранить» шлёт всё изменённое). Добавить известного —
/// значит получить его в `items` дважды, то есть задвоенную строку в каждом
/// списке, построенном по контроллеру: ошибка того же класса, что чинится,
/// только в другую сторону.
///
/// **И добавлять надо ТОТ ЖЕ экземпляр, который отдал вызывающий.** Сервер
/// возвращает свои объекты; если положить в список их, у вызывающего на руках
/// останется прежний экземпляр, и один объект окажется на экране дважды —
/// как «свой» и как «из контроллера». Поэтому предпочитаем элемент из
/// [postedItems], а объект сервера берём только если пары не нашлось.
///
/// Вынесено отдельной функцией, чтобы проверяться тестом без сети и без
/// поднятого контроллера.
library;

import 'package:nsg_data/nsg_data.dart';

/// Переносит значения, вернувшиеся с сервера, в объекты вызывающего и в
/// мастер-список контроллера; недостающие в списке — дописывает.
///
/// [postedItems] — то, что отправляли (`itemsToPost`);
/// [serverItems] — то, что вернул сервер;
/// [dataItemList] — мастер-список контроллера, меняется на месте.
///
/// Возвращает элементы, которые были **добавлены** в [dataItemList] — пусто,
/// если добавлять было нечего. Вызывающий по этому признаку решает, нужна ли
/// пересортировка списка.
List<NsgDataItem> applyPostedItems({
  required List<NsgDataItem> postedItems,
  required List<NsgDataItem> serverItems,
  required List<NsgDataItem> dataItemList,
}) {
  final added = <NsgDataItem>[];
  for (final item in serverItems) {
    NsgDataItem? posted;
    for (final e in postedItems) {
      if (e.id == item.id) {
        posted = e;
        break;
      }
    }
    if (posted != null) {
      posted.copyFieldValues(item);
      posted.state = NsgDataItemState.fill;
    }

    NsgDataItem? known;
    for (final e in dataItemList) {
      if (e.id == item.id) {
        known = e;
        break;
      }
    }
    if (known != null) {
      known.copyFieldValues(item);
      known.state = NsgDataItemState.fill;
      continue;
    }

    // Элемента в мастер-списке не было — значит его только что создали.
    // Кладём экземпляр вызывающего, чтобы не разводить личности; повторный
    // проход по тому же id уже найдёт его выше и добавления не повторит.
    final toAdd = posted ?? item;
    if (posted == null) {
      toAdd.state = NsgDataItemState.fill;
    }
    dataItemList.add(toAdd);
    added.add(toAdd);
  }
  return added;
}
