/// Различение промаха кэша ссылок (NSG-SOFT/futbolista-tasks#1751).
///
/// `getReferent` на промахе возвращает ПУСТЫШКУ — свежий объект того же типа.
/// Снаружи она неотличима от честного «ссылка не заполнена»: у обеих нулевые
/// поля, дефолтные перечисления, пустые строки. Дальше код сравнивает её с
/// чем-то, не совпадает — и молча уходит по ветке «нет данных».
///
/// И это не косметика. `NsgDataItem.operator ==` сравнивает по ключевому полю,
/// поэтому две пустышки одного типа РАВНЫ: проверка «эти объекты ссылаются на
/// одно и то же» даёт `true` там, где оба просто недочитаны. А как ключ словаря
/// пустышка с заполненным объектом не совпадает — и группировка разъезжается.
///
/// Цена, уже заплаченная в приложениях на этом фреймворке:
/// * счёт матча не обновлялся на табло — сравнение `currentItem != items.first.match`
///   на промахе не совпадало, и метод выходил при полностью корректных данных;
/// * «свой регламент или родительский» решалось сравнением объектов, и на
///   промахе правка дочернего уровня записывалась в объект родителя;
/// * в заголовке карточки появлялась строка вида `Экран 1 --->  - ` — выглядит
///   как данные, данными не является.
///
/// Здесь то, чего не хватало во всех трёх случаях: промах становится ОТДЕЛЬНЫМ
/// состоянием, которое вызывающий может проверить, а не веткой «нет данных», в
/// которую код сваливается молча. Само поведение `getReferent` не меняется —
/// пустышка остаётся, на неё опирается работающий код.
///
/// Правило нарочно чистое: строка-ссылка плюс факт разрешения, никакого
/// обращения к кэшу. Точка входа для живого объекта — [NsgDataItem.referentState]
/// и [NsgDataItem.referentIfLoaded].
library;

/// `Guid.Empty` строкой. Дублирует `Guid.Empty`, чтобы файл правила не тянул
/// зависимостей: значение — часть формата ссылки, а не деталь реализации.
const String _emptyGuid = '00000000-0000-0000-0000-000000000000';

/// Состояние ссылки, различимое ТОЛЬКО вместе со строкой-ссылкой.
///
/// По одному объекту-референту эти три состояния неразличимы: во всех трёх
/// случаях `getReferent` отдаёт объект, и в двух из трёх он пустой.
enum NsgReferentState {
  /// Ссылка не заполнена. Пустышка честная, данных нет и не должно быть.
  notSet,

  /// Ссылка ЗАДАНА, а объекта по ней нет: его не дочитали — поля нет в
  /// `referenceList` запроса, либо объект не доехал в кэш.
  ///
  /// Это дефект выборки, а не состояние данных. Экран покажет пустоту, ошибки
  /// нигде не будет.
  missing,

  /// Объект дочитан, читать его поля можно.
  loaded,
}

/// Заполнена ли ссылка — решение по СТРОКЕ, а не по объекту.
///
/// Понимает оба формата: типизированная ссылка — голый guid, нетипизированная —
/// `{guid}.{ТипОбъекта}` (см. `UntypedId`). «Пусто» в этих форматах приезжает
/// несколькими способами сразу: `''`, нулевой guid, нулевой guid с суффиксом
/// типа и один суффикс без guid — сервер кладёт то один вариант, то другой.
bool nsgReferenceIsSet(String rawReference) {
  final raw = rawReference.trim();
  if (raw.isEmpty) return false;
  final guid = raw.split('.').first.trim();
  if (guid.isEmpty) return false;
  return guid.toLowerCase() != _emptyGuid;
}

/// Чистое правило: три состояния из двух фактов.
///
/// [rawReference] — значение ссылочного поля как строка.
/// [referentResolved] — нашёлся ли объект в кэше; это чтение С `allowNull`,
/// которое пустышку не подставляет.
///
/// Ключевая строка — вторая: заполненная ссылка без объекта это [NsgReferentState.missing],
/// а не [NsgReferentState.notSet]. Ровно этого различия у вызывающего и не было.
NsgReferentState nsgReferentStateOf({required String rawReference, required bool referentResolved}) {
  if (!nsgReferenceIsSet(rawReference)) return NsgReferentState.notSet;
  return referentResolved ? NsgReferentState.loaded : NsgReferentState.missing;
}
